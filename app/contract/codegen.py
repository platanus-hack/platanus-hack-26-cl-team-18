"""Generate the TS side of the wire contract (zod schemas + inferred types).

Input: the Pydantic models in `app.contract.messages`, read in serialization
mode with defaults marked required: the backend always emits every field, so
the TS types carry no optionality the wire doesn't have. Output: one TS module,
`web/src/contract/messages.gen.ts`. Run via `make contract`; never edit the
output by hand. The generator covers exactly the JSON Schema subset the
contract uses and fails loudly on anything else, so a new construct can't be
silently mistranslated.

Cross-field `model_validator`s (e.g. `looking <= people`) are not expressible
in JSON Schema; the backend enforces them on receipt.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from app.contract import messages

OUTPUT_PATH = "web/src/contract/messages.gen.ts"

_HEADER = """\
// GENERATED by `make contract` from app/contract/messages.py. DO NOT EDIT.
// Every inbound WebSocket frame must pass through one of these schemas.
/* eslint-disable */
import {{ z }} from "zod";

export const CONTRACT_VERSION = {version} as const;
"""


class UnsupportedSchema(Exception):
    pass


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _deps(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, Mapping):
        if "$ref" in node:
            found.add(_ref_name(node["$ref"]))
        for value in node.values():
            found |= _deps(value)
    elif isinstance(node, list):
        for value in node:
            found |= _deps(value)
    return found


def _topo_order(defs: Mapping[str, Any]) -> list[str]:
    order: list[str] = []
    state: dict[str, int] = {}

    def visit(name: str) -> None:
        if state.get(name) == 2:
            return
        if state.get(name) == 1:
            raise UnsupportedSchema(f"recursive schema {name!r} is not supported")
        state[name] = 1
        for dep in sorted(_deps(defs[name])):
            visit(dep)
        state[name] = 2
        order.append(name)

    for name in defs:
        visit(name)
    return order


def _js(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _regex(pattern: str) -> str:
    return "/" + pattern.replace("/", "\\/") + "/"


def _string(node: Mapping[str, Any]) -> str:
    if node.get("format") == "date-time":
        return "z.iso.datetime({ offset: true })"
    out = "z.string()"
    if "minLength" in node:
        out += f".min({node['minLength']})"
    if "maxLength" in node:
        out += f".max({node['maxLength']})"
    if "pattern" in node:
        out += f".regex({_regex(node['pattern'])})"
    return out


def _number(node: Mapping[str, Any], *, integer: bool) -> str:
    out = "z.number().int()" if integer else "z.number()"
    if "minimum" in node:
        out += f".gte({node['minimum']})"
    if "exclusiveMinimum" in node:
        out += f".gt({node['exclusiveMinimum']})"
    if "maximum" in node:
        out += f".lte({node['maximum']})"
    if "exclusiveMaximum" in node:
        out += f".lt({node['exclusiveMaximum']})"
    return out


def _expr(node: Mapping[str, Any]) -> str:
    if "$ref" in node:
        return f"{_ref_name(node['$ref'])}Schema"
    if "const" in node:
        return f"z.literal({_js(node['const'])})"
    if "enum" in node:
        return "z.enum([" + ", ".join(_js(v) for v in node["enum"]) + "])"
    if "anyOf" in node:
        options = [o for o in node["anyOf"] if o.get("type") != "null"]
        nullable = len(options) != len(node["anyOf"])
        if len(options) != 1:
            raise UnsupportedSchema(f"non-nullable anyOf is not supported: {node}")
        inner = _expr(options[0])
        return f"{inner}.nullable()" if nullable else inner
    kind = node.get("type")
    if kind == "string":
        return _string(node)
    if kind == "integer":
        return _number(node, integer=True)
    if kind == "number":
        return _number(node, integer=False)
    if kind == "boolean":
        return "z.boolean()"
    if kind == "array":
        out = f"z.array({_expr(node['items'])})"
        if "minItems" in node:
            out += f".min({node['minItems']})"
        if "maxItems" in node:
            out += f".max({node['maxItems']})"
        return out
    raise UnsupportedSchema(f"unsupported schema node: {node}")


def _object(name: str, node: Mapping[str, Any]) -> str:
    if node.get("type") != "object" or node.get("additionalProperties") is not False:
        raise UnsupportedSchema(f"{name}: only strict objects are supported")
    required = set(node.get("required", []))
    lines = []
    for field, spec in node["properties"].items():
        expr = _expr(spec)
        if field not in required:
            if "default" in spec:
                expr += f".default({_js(spec['default'])})"
            elif spec.get("type") == "array":
                expr += ".default([])"
            else:
                expr += ".optional()"
        lines.append(f"  {field}: {expr},")
    body = "\n".join(lines)
    return f"z.strictObject({{\n{body}\n}})"


def _definition(name: str, node: Mapping[str, Any]) -> str:
    doc = node.get("description")
    comment = "".join(f"// {line}\n" for line in doc.splitlines()) if doc else ""
    expr = _expr(node) if "enum" in node else _object(name, node)
    return (
        f"{comment}export const {name}Schema = {expr};\n"
        f"export type {name} = z.infer<typeof {name}Schema>;\n"
    )


def _union(name: str, members: tuple[type[BaseModel], ...]) -> str:
    refs = ", ".join(f"{m.__name__}Schema" for m in members)
    return (
        f'export const {name}Schema = z.discriminatedUnion("type", [{refs}]);\n'
        f"export type {name} = z.infer<typeof {name}Schema>;\n"
    )


def render() -> str:
    _, top = models_json_schema(
        [(m, "serialization") for m in messages.ALL_MESSAGES],
        ref_template="#/$defs/{model}",
    )
    defs: dict[str, Any] = top["$defs"]
    parts = [_HEADER.format(version=messages.CONTRACT_VERSION)]
    parts += [_definition(name, defs[name]) for name in _topo_order(defs)]
    parts += [_union(name, members) for name, members in messages.SOCKET_UNIONS.items()]
    types = ", ".join(_js(m.model_fields["type"].default) for m in messages.ALL_MESSAGES)
    parts.append(f"export const MESSAGE_TYPES = [{types}] as const;\n")
    parts.append("export type MessageType = (typeof MESSAGE_TYPES)[number];\n")
    return "\n".join(parts)
